-- Group 040, Feature 046 (Song Sharing and Comments): public comments on a song.
-- API: GET and POST /api/v1/songs/:id/comments, DELETE /api/v1/comments/:id
-- (docs/analysis-and-design/api-contract.md). Anyone can read, signed-in users can post,
-- and only the author or an administrator can delete (enforced by the backend).
-- Follows the team ER naming (song_id -> songs.song_id, user_id -> users.user_id).
-- The optional `timestamp_seconds` of the API contract is not used by Feature 046.
-- Safe to re-run.

BEGIN;

CREATE TABLE IF NOT EXISTS public.song_comments (
  comment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  song_id bigint NOT NULL REFERENCES public.songs(song_id) ON DELETE CASCADE,
  user_id text NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
  content text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

DO $check$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conrelid = 'public.song_comments'::regclass
                    AND conname = 'song_comments_content_length_check') THEN
    -- 046-FR-009: 1 to 300 characters after trimming.
    ALTER TABLE public.song_comments
      ADD CONSTRAINT song_comments_content_length_check
      CHECK (char_length(btrim(content)) BETWEEN 1 AND 300);
  END IF;
END;
$check$;

-- Newest comments of one song first.
CREATE INDEX IF NOT EXISTS idx_song_comments_song_newest
  ON public.song_comments (song_id, comment_id DESC);
CREATE INDEX IF NOT EXISTS idx_song_comments_user
  ON public.song_comments (user_id);

-- Only the backend (service role) reads and writes comments; permissions are checked there.
ALTER TABLE public.song_comments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.song_comments FROM anon, authenticated;

COMMIT;

