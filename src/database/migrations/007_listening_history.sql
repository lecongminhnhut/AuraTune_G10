-- Group 040 (041-FR-014): play events for the Music Player.
-- Matches the team ER design (docs/design/database/er-diagram.md) and the shared Supabase
-- project: listening_history(history_id, user_id -> users.user_id, song_id -> songs.song_id,
-- played_at, duration_listened in seconds). On the shared project the table already exists,
-- so this script only adds what is missing. Safe to re-run.

BEGIN;

CREATE TABLE IF NOT EXISTS public.listening_history (
  history_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text REFERENCES public.users(user_id) ON DELETE CASCADE,
  song_id bigint REFERENCES public.songs(song_id) ON DELETE CASCADE,
  played_at timestamptz DEFAULT now(),
  duration_listened integer
);

ALTER TABLE public.listening_history ADD COLUMN IF NOT EXISTS duration_listened integer;

DO $check$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conrelid = 'public.listening_history'::regclass
                    AND conname = 'listening_history_duration_listened_check') THEN
    ALTER TABLE public.listening_history
      ADD CONSTRAINT listening_history_duration_listened_check CHECK (duration_listened IS NULL OR duration_listened >= 0);
  END IF;
END;
$check$;

CREATE INDEX IF NOT EXISTS idx_listening_history_user_played
  ON public.listening_history (user_id, played_at);

-- Only the backend (service role) reads and writes play events.
ALTER TABLE public.listening_history ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.listening_history FROM anon, authenticated;

COMMIT;

NOTIFY pgrst, 'reload schema';
